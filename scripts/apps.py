#!/usr/bin/env python3
"""Manage the app directory: regenerate the manifest, or scaffold a new app.

A browser cannot list a directory over static HTTP, so "drop a folder in and it appears"
needs exactly one generated index. This writes it.

    scripts/apps.py                 regenerate apps/manifest.mjs from the folders on disk
    scripts/apps.py --new clock     scaffold apps/clock/ and regenerate
    scripts/apps.py --check         exit 1 if the manifest disagrees with the folders

`--check` exists so a stale manifest fails a run rather than quietly leaving an app out.
Nothing here imports or parses JavaScript: the folder names are the whole input, and the
loader validates the specs at runtime where it can actually read them.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
APPS_DIR = REPO_ROOT / "apps"
MANIFEST = APPS_DIR / "manifest.mjs"

#: An app id is a folder name, and it also becomes a CSS class (`app-<id>`) and part of a
#: URL. Lower-case, digits and dashes keep it valid in all three without escaping.
ID_PATTERN = re.compile(r"^[a-z][a-z0-9-]*$")

HEADER = """/* The app directory.
 *
 * Generated by `scripts/apps.py`. Do not edit by hand: the next run will overwrite it.
 *
 * A browser cannot list a directory over static HTTP, so this file is how the desktop knows
 * which folders under `apps/` exist. Order is the Start menu's order.
 */
export const APPS = [
"""

FOOTER = "];\n"

APP_MJS = '''/* {title} — see docs/apps.md for the contract this file follows. */

export default {{
  id: '{id}',
  name: '{title}',
  icon: 'window',
  width: 480,
  height: 320,
  status: true,
  onDesktop: true,
  styles: ['app.css'],

  mount({{ win }}) {{
    win.setStatus('Ready');

    const root = document.createElement('div');
    root.className = 'sheet';

    const heading = document.createElement('h2');
    heading.textContent = '{title}';

    const body = document.createElement('p');
    body.textContent = 'Replace this with the app. Everything it needs lives in this folder.';

    root.append(heading, body);
    return root;
  }},
}};
'''

APP_CSS = '''/* {title}'s own styles.
 *
 * Scoped under `.app-{id}`, which the loader puts on this app's window body. Rules outside
 * that selector would reach into every other app's windows.
 */

.app-{id} h2 {{
  margin: 0 0 .5rem;
  font-size: 13px;
  color: #0a2a5a;
}}
'''


def discovered() -> list[str]:
    """Every folder under `apps/` that has an `app.mjs`, sorted.

    Sorted rather than in filesystem order, so the manifest is stable across machines and a
    regeneration produces no spurious diff.
    """
    if not APPS_DIR.is_dir():
        return []
    found = []
    for child in sorted(APPS_DIR.iterdir()):
        if not child.is_dir() or child.name.startswith("."):
            continue
        if not (child / "app.mjs").is_file():
            print(f"  skipped {child.name}/ — no app.mjs", file=sys.stderr)
            continue
        if not ID_PATTERN.match(child.name):
            print(
                f"  skipped {child.name}/ — an app id must match {ID_PATTERN.pattern}",
                file=sys.stderr,
            )
            continue
        found.append(child.name)
    return found


def render(ids: list[str]) -> str:
    return HEADER + "".join(f"  '{app_id}',\n" for app_id in ids) + FOOTER


def listed() -> list[str]:
    """The ids currently in the manifest, read without executing it."""
    if not MANIFEST.is_file():
        return []
    return re.findall(r"^\s*'([^']+)',$", MANIFEST.read_text(encoding="utf-8"), re.MULTILINE)


def scaffold(app_id: str) -> int:
    if not ID_PATTERN.match(app_id):
        print(f"'{app_id}' is not a usable app id: must match {ID_PATTERN.pattern}", file=sys.stderr)
        return 1
    folder = APPS_DIR / app_id
    if folder.exists():
        print(f"apps/{app_id}/ already exists", file=sys.stderr)
        return 1

    title = app_id.replace("-", " ").title()
    folder.mkdir(parents=True)
    (folder / "app.mjs").write_text(APP_MJS.format(id=app_id, title=title), encoding="utf-8")
    (folder / "app.css").write_text(APP_CSS.format(id=app_id, title=title), encoding="utf-8")
    print(f"created apps/{app_id}/app.mjs")
    print(f"created apps/{app_id}/app.css")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--new", metavar="ID", help="scaffold a new app folder")
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if the manifest disagrees with the folders on disk",
    )
    args = parser.parse_args(argv)

    if args.new:
        if scaffold(args.new):
            return 1

    ids = discovered()

    if args.check:
        current = listed()
        if current != ids:
            print("apps/manifest.mjs is stale.", file=sys.stderr)
            missing = [i for i in ids if i not in current]
            extra = [i for i in current if i not in ids]
            if missing:
                print(f"  on disk but not listed: {', '.join(missing)}", file=sys.stderr)
            if extra:
                print(f"  listed but not on disk: {', '.join(extra)}", file=sys.stderr)
            if not missing and not extra:
                print(f"  same apps, different order: {current} vs {ids}", file=sys.stderr)
            print("  run scripts/apps.py to regenerate.", file=sys.stderr)
            return 1
        print(f"apps/manifest.mjs is current ({len(ids)} apps)")
        return 0

    APPS_DIR.mkdir(exist_ok=True)
    MANIFEST.write_text(render(ids), encoding="utf-8")
    print(f"wrote apps/manifest.mjs with {len(ids)} apps: {', '.join(ids) or '(none)'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
